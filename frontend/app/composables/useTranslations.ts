const activeLocaleKey = "app_locale"
const translationCache: TranslationCache = {}

export const useTranslations = () => {
  const translationApi = useTranslationApi()
  const locale = useState<Locale>("current_locale", () => "uz")
  const loadedLocale = useState<Locale | null>("loaded_locale", () => null)
  const translations = useState<Record<string, string>>("current_translations", () => ({ ...FALLBACK_TRANSLATIONS.uz }))

  const load = async (nextLocale?: Locale, force = false) => {
    const targetLocale = nextLocale ?? locale.value
    if (!force && loadedLocale.value === targetLocale && Object.keys(translations.value).length > 0) {
      return
    }

    if (import.meta.client) {
      const savedLocale = localStorage.getItem(activeLocaleKey) as Locale | null
      if (!nextLocale && savedLocale && ["uz", "ru", "en"].includes(savedLocale)) {
        locale.value = savedLocale
      }
    }

    const resolvedLocale = nextLocale ?? locale.value
    const fallback = FALLBACK_TRANSLATIONS[resolvedLocale] ?? FALLBACK_TRANSLATIONS.uz

    if (!force && translationCache[resolvedLocale]) {
      translations.value = { ...fallback, ...translationCache[resolvedLocale] }
      locale.value = resolvedLocale
      loadedLocale.value = resolvedLocale
      return
    }

    try {
      const remote = await translationApi.list(resolvedLocale)
      translationCache[resolvedLocale] = remote.translations
      translations.value = { ...fallback, ...remote.translations }
    } catch {
      translations.value = { ...fallback }
    }

    locale.value = resolvedLocale
    loadedLocale.value = resolvedLocale

    if (import.meta.client) {
      localStorage.setItem(activeLocaleKey, resolvedLocale)
    }
  }

  const setLocale = async (nextLocale: Locale) => {
    await load(nextLocale, true)
  }

  const t = (code: string, params?: Record<string, string | number>) => {
    let text = translations.value[code] || FALLBACK_TRANSLATIONS[locale.value]?.[code] || FALLBACK_TRANSLATIONS.uz[code] || code
    if (params) {
      Object.entries(params).forEach(([key, val]) => {
        text = text.replace(new RegExp(`\\{${key}\\}`, 'g'), String(val))
      })
    }
    return text
  }

  return {
    locale,
    translations,
    load,
    setLocale,
    t,
  }
}
